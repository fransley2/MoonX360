def find_bundle(explicit: Path | None) -> Path:
    if explicit:
        if not explicit.is_file():
            raise SystemExit(f"CA bundle not found: {explicit}")
        return explicit
    for candidate in DEFAULT_BUNDLES:
        if candidate.is_file():
            return candidate
    raise SystemExit("No system CA bundle found; pass --bundle")


def load_by_sha256(bundle: Path) -> dict[str, bytes]:
    text = bundle.read_text(encoding="utf-8", errors="replace")
    certs: dict[str, bytes] = {}
    for pem in re.findall(r"-----BEGIN CERTIFICATE-----.*?-----END CERTIFICATE-----", text, re.S):
        cert = x509.load_pem_x509_certificate(pem.encode("ascii"))
        der = cert.public_bytes(serialization.Encoding.DER)
        certs[hashlib.sha256(der).hexdigest()] = der
    return certs


def main() -> None:
    root_dir = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--bundle", type=Path, help="Path to PEM CA trust bundle")
    parser.add_argument(
        "--out-dir",
        type=Path,
        default=root_dir / "src" / "update",
        help="Destination directory for update_tls_roots.h/.c",
    )
    args = parser.parse_args()

    bundle = find_bundle(args.bundle)
    by_fp = load_by_sha256(bundle)

    out_dir = args.out_dir
    out_dir.mkdir(parents=True, exist_ok=True)

    header = """#pragma once
/* Generated by tools/generate_tls_roots.py. Do not edit by hand. */
#include <stddef.h>

#ifdef __cplusplus
extern "C" {
#endif

struct update_tls_root {
    const char *name;
    const unsigned char *der;
    size_t len;
};

extern const struct update_tls_root g_update_tls_roots[];
extern const int g_update_tls_root_count;

#ifdef __cplusplus
}
#endif
"""

    lines = [
        "/* Generated by tools/generate_tls_roots.py from system CA bundle. Do not edit by hand. */",
        '#include "update_tls_roots.h"',
        "",
    ]
    entries = []
    for idx, (label, fp) in enumerate(ROOT_SPECS):
        der = by_fp.get(fp)
        if der is None:
            raise SystemExit(f"Required CA root missing from bundle ({bundle}): {label} ({fp})")
        lines.append(f"/* {label} | SHA-256: {fp} */")
        lines.append(f"static const unsigned char k_update_root_{idx}[{len(der)}] = {{")
        for off in range(0, len(der), 16):
            chunk = ", ".join(f"0x{b:02X}" for b in der[off:off + 16])
            lines.append(f"    {chunk},")
        lines.append("};")
        lines.append("")
        entries.append(f'    {{ "{label}", k_update_root_{idx}, sizeof(k_update_root_{idx}) }},')

    lines.append("const struct update_tls_root g_update_tls_roots[] = {")
    lines.extend(entries)
    lines.append("};")
    lines.append(f"const int g_update_tls_root_count = {len(entries)};")
    lines.append("")

    (out_dir / "update_tls_roots.h").write_text(header, encoding="utf-8", newline="\n")
    (out_dir / "update_tls_roots.c").write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"Generated {len(entries)} TLS roots from {bundle}")


if __name__ == "__main__":
    main()
