"""Generate an Ed25519 update signing keypair outside the source tree and optionally emit public key header."""
import argparse
import os
from pathlib import Path
import tempfile

from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric import ed25519

REPO_ROOT = Path(__file__).resolve().parents[1]


def atomic_write(path: Path, data: bytes) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp_name = tempfile.mkstemp(prefix=path.name + ".", dir=path.parent)
    try:
        with os.fdopen(fd, "wb") as handle:
            handle.write(data)
        os.replace(tmp_name, path)
    finally:
        if os.path.exists(tmp_name):
            os.unlink(tmp_name)


def is_inside_repo(path: Path) -> bool:
    try:
        path.resolve().relative_to(REPO_ROOT.resolve())
        return True
    except ValueError:
        return False


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--key", type=Path, required=True, help="Explicit output path for private Ed25519 PEM key")
    parser.add_argument("--header", type=Path, help="Optional C header output path for embedded 64-hex public key")
    parser.add_argument("--test-config-header", type=Path, help="Optional disposable test config header path (with test base URL)")
    parser.add_argument("--test-base-url", help="Base URL written to --test-config-header (for local test kits only)")
    parser.add_argument("--allow-in-repo", action="store_true", help="Allow writing disposable test keys under .work/ only")
    parser.add_argument("--force", action="store_true", help="Overwrite an existing key file")
    args = parser.parse_args()

    key_path = args.key.expanduser().resolve()
    if is_inside_repo(key_path):
        work_root = (REPO_ROOT / ".work").resolve()
        try:
            key_path.relative_to(work_root)
            in_work = True
        except ValueError:
            in_work = False
        if not (args.allow_in_repo and in_work):
            raise SystemExit("Refusing to write private signing key inside repository; store production keys outside git or pass --allow-in-repo inside .work/")

    if key_path.exists() and not args.force:
        raise SystemExit(f"Key file already exists (pass --force to overwrite): {key_path}")

    priv = ed25519.Ed25519PrivateKey.generate()
    pub_raw = priv.public_key().public_bytes(serialization.Encoding.Raw, serialization.PublicFormat.Raw)
    pub_hex = pub_raw.hex()
    priv_pem = priv.private_bytes(
        serialization.Encoding.PEM,
        serialization.PrivateFormat.PKCS8,
        serialization.NoEncryption(),
    )

    key_path.parent.mkdir(parents=True, exist_ok=True)
    atomic_write(key_path, priv_pem)
    try:
        os.chmod(key_path, 0o600)
    except OSError:
        pass

    if args.header:
        header_text = (
            "#pragma once\n"
            "/* Embedded Ed25519 public verification key for MoonX360 signed updates.\n"
            " * Generated by tools/generate_update_key.py. Never embed private keys. */\n"
            "#ifdef MOONX_UPDATE_TEST_CONFIG\n"
            "#include MOONX_UPDATE_TEST_CONFIG\n"
            "#if !defined(MOONX_UPDATE_PUBLIC_KEY_HEX) || !defined(MOONX_UPDATE_TEST_BASE_URL)\n"
            "#error Incomplete MOONX_UPDATE_TEST_CONFIG header\n"
            "#endif\n"
            "#else\n"
            f'#define MOONX_UPDATE_PUBLIC_KEY_HEX "{pub_hex}"\n'
            "#endif\n"
        )
        atomic_write(args.header, header_text.encode("utf-8"))

    if args.test_config_header:
        if not args.test_base_url:
            raise SystemExit("--test-config-header requires --test-base-url")
        base = args.test_base_url if args.test_base_url.endswith("/") else args.test_base_url + "/"
        test_header = (
            "#pragma once\n"
            "/* Disposable test-kit update configuration. Never ship in production builds. */\n"
            f'#define MOONX_UPDATE_PUBLIC_KEY_HEX "{pub_hex}"\n'
            f'#define MOONX_UPDATE_TEST_BASE_URL "{base}"\n'
        )
        atomic_write(args.test_config_header, test_header.encode("utf-8"))

    print(f"Created Ed25519 key at {key_path}")
    print(f"Public key hex: {pub_hex}")


if __name__ == "__main__":
    main()
